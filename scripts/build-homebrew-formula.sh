#!/usr/bin/env bash
# Prints the Homebrew formula for one agent release.
#
#   scripts/build-homebrew-formula.sh 0.4.21 > Formula/usejunction.rb
#   scripts/build-homebrew-formula.sh 0.4.21 path/to/checksums.txt
#
# The formula installs the release's prebuilt binary and nothing else: no
# background service, no sign-in. Without a checksums file, the release's own
# checksums.txt is downloaded.
set -euo pipefail

VERSION="${1:-}"
CHECKSUMS_FILE="${2:-}"
if [[ ! "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "Usage: $0 <version> [checksums.txt]   (version like 0.4.21)" >&2
  exit 2
fi

BASE="https://github.com/use-junction/usejunction/releases/download/agent-v${VERSION}"
if [[ -n "$CHECKSUMS_FILE" ]]; then
  CHECKSUMS="$(cat "$CHECKSUMS_FILE")"
else
  CHECKSUMS="$(curl -fsSL "${BASE}/checksums.txt")"
fi

checksum_for() {
  local name="$1" sum
  sum="$(awk -v name="$name" '$2 == name { print $1 }' <<<"$CHECKSUMS")"
  if [[ ! "$sum" =~ ^[0-9a-f]{64}$ ]]; then
    echo "Release ${VERSION} lists no checksum for ${name}." >&2
    exit 1
  fi
  printf '%s' "$sum"
}

DARWIN_ARM64="$(checksum_for usejunction-darwin-arm64)"
DARWIN_AMD64="$(checksum_for usejunction-darwin-amd64)"
LINUX_ARM64="$(checksum_for usejunction-linux-arm64)"
LINUX_AMD64="$(checksum_for usejunction-linux-amd64)"

cat <<FORMULA
# Generated by scripts/build-homebrew-formula.sh in use-junction/usejunction.
# Do not edit by hand; run the script for the new release instead.
class Usejunction < Formula
  desc "See what your AI coding tools cost, from the logs on this machine"
  homepage "https://usejunction.dev"
  version "${VERSION}"
  license :cannot_represent

  on_macos do
    on_arm do
      url "${BASE}/usejunction-darwin-arm64"
      sha256 "${DARWIN_ARM64}"
    end
    on_intel do
      url "${BASE}/usejunction-darwin-amd64"
      sha256 "${DARWIN_AMD64}"
    end
  end

  on_linux do
    on_arm do
      url "${BASE}/usejunction-linux-arm64"
      sha256 "${LINUX_ARM64}"
    end
    on_intel do
      url "${BASE}/usejunction-linux-amd64"
      sha256 "${LINUX_AMD64}"
    end
  end

  def install
    bin.install Dir["usejunction-*"].first => "usejunction"
  end

  def caveats
    <<~EOS
      Run \`usejunction\` for a usage table. No account is needed and nothing is uploaded.

      To see charts, cost by repo and your whole team, install the full agent and sign in:
        curl -fsSL https://usejunction.dev/install.sh | bash
    EOS
  end

  test do
    assert_match "usejunction", shell_output("#{bin}/usejunction --help")
  end
end
FORMULA
